import { buildSetClause } from "../db/patch.ts";
import { pool } from "../db/pool.ts";
import {
  assignedHelpersColumn,
  assignHelpers,
  assignmentArrays,
  jobHelpers,
  unassignOtherHelpers,
} from "../helpers/assigned.ts";
import type { AssignedHelper, HelperAssignment } from "../helpers/assigned.ts";

export const serviceTypes = ["regular", "deep", "move_in", "move_out"] as const;
export type ServiceType = (typeof serviceTypes)[number];

export const jobStatuses = [
  "estimated",
  "scheduled",
  "completed",
  "cancelled",
] as const;
export type JobStatus = (typeof jobStatuses)[number];

export type Job = {
  id: string;
  scheduledDate: string; // YYYY-MM-DD
  startTime: string; // HH:MM:SS
  durationMinutes: number;
  serviceType: ServiceType;
  status: JobStatus;
  hourlyRateCents: number;
  // An agreed price; when null, priceCents is hourly rate x duration.
  fixedPriceCents: number | null;
  priceCents: number;
  notes: string | null;
  property: {
    id: string;
    addressLine1: string;
    addressLine2: string | null;
    city: string;
    province: string;
    postalCode: string;
    country: string;
    notes: string | null;
  };
  client: { id: string; name: string };
  // Who does the job, by name; empty while nobody is assigned. Each is paid
  // their usual rate unless the job has one of its own for them.
  helpers: AssignedHelper[];
  // Set on jobs generated by a recurring series; they stay linked even when
  // edited on their own.
  recurringSeriesId: string | null;
  // A job is invoiced when an invoice points at it (project brief, design
  // rule 3); nothing on the job itself says so.
  invoice: { id: string; number: number } | null;
  createdAt: Date;
  updatedAt: Date;
};

export type NewJob = {
  propertyId: string;
  scheduledDate: string;
  startTime: string;
  durationMinutes: number;
  serviceType: ServiceType;
  status?: JobStatus;
  hourlyRateCents: number;
  fixedPriceCents?: number | null;
  helpers?: HelperAssignment[];
  notes?: string | null;
};

// Only the keys present are updated; null clears a field, and `helpers`
// replaces the helpers the job had.
// The property is chosen at creation: to move a job, delete and recreate it.
export type JobPatch = Partial<Omit<NewJob, "propertyId">>;

// The helpers are not a column: they are rows of their own.
const patchableColumns: Record<Exclude<keyof JobPatch, "helpers">, string> = {
  scheduledDate: "scheduled_date",
  startTime: "start_time",
  durationMinutes: "duration_minutes",
  serviceType: "service_type",
  status: "status",
  hourlyRateCents: "hourly_rate_cents",
  fixedPriceCents: "fixed_price_cents",
  notes: "notes",
};

// Every read joins the property, its client and the invoice and lists the
// helpers: the calendar shows them with each job, and a separate request per
// job would be wasteful.
const columns = `
  j.id,
  j.scheduled_date AS "scheduledDate",
  j.start_time AS "startTime",
  j.duration_minutes AS "durationMinutes",
  j.service_type AS "serviceType",
  j.status,
  j.hourly_rate_cents AS "hourlyRateCents",
  j.fixed_price_cents AS "fixedPriceCents",
  COALESCE(
    j.fixed_price_cents,
    round(j.hourly_rate_cents * j.duration_minutes / 60.0)::integer
  ) AS "priceCents",
  j.notes,
  json_build_object(
    'id', p.id,
    'addressLine1', p.address_line1,
    'addressLine2', p.address_line2,
    'city', p.city,
    'province', p.province,
    'postalCode', p.postal_code,
    'country', p.country,
    'notes', p.notes
  ) AS property,
  json_build_object('id', c.id, 'name', c.name) AS client,
  ${assignedHelpersColumn(jobHelpers, "j")},
  j.recurring_series_id AS "recurringSeriesId",
  CASE WHEN i.id IS NULL THEN NULL
       ELSE json_build_object('id', i.id, 'number', i.number)
  END AS invoice,
  j.created_at AS "createdAt",
  j.updated_at AS "updatedAt"
`;

const joins = `
  JOIN properties p
    ON p.organization_id = j.organization_id AND p.id = j.property_id
  JOIN clients c
    ON c.organization_id = p.organization_id AND c.id = p.client_id
  LEFT JOIN invoices i
    ON i.organization_id = j.organization_id AND i.job_id = j.id
`;

export async function listJobs(
  organizationId: string,
  range: { from: string; to: string },
): Promise<Job[]> {
  const { rows } = await pool.query<Job>(
    `SELECT ${columns} FROM jobs j ${joins}
     WHERE j.organization_id = $1 AND j.scheduled_date BETWEEN $2 AND $3
     ORDER BY j.scheduled_date, j.start_time, j.id`,
    [organizationId, range.from, range.to],
  );
  return rows;
}

export async function findJob(
  organizationId: string,
  id: string,
): Promise<Job | undefined> {
  const { rows } = await pool.query<Job>(
    `SELECT ${columns} FROM jobs j ${joins}
     WHERE j.organization_id = $1 AND j.id = $2`,
    [organizationId, id],
  );
  return rows[0];
}

// Returns undefined when the property does not exist in the organization:
// the SELECT finds no property, so nothing is inserted. An INSERT ... SELECT
// cannot use the DEFAULT keyword, hence the COALESCE mirroring the default.
// The job and its helpers are written by one statement, which cannot read
// back the helpers it wrote: the job is read once it is there.
export async function createJob(
  organizationId: string,
  input: NewJob,
): Promise<Job | undefined> {
  const { rows } = await pool.query<{ id: string }>(
    `WITH inserted AS (
       INSERT INTO jobs (
         organization_id, property_id, scheduled_date, start_time,
         duration_minutes, service_type, status, hourly_rate_cents,
         fixed_price_cents, notes
       )
       SELECT organization_id, id, $3, $4, $5, $6, COALESCE($7, 'scheduled'),
              $8, $9, $10
       FROM properties
       WHERE organization_id = $1 AND id = $2
       RETURNING organization_id, id
     ),
     ${assignHelpers(jobHelpers, "inserted", "$11", "$12")}
     SELECT id FROM inserted`,
    [
      organizationId,
      input.propertyId,
      input.scheduledDate,
      input.startTime,
      input.durationMinutes,
      input.serviceType,
      input.status ?? null,
      input.hourlyRateCents,
      input.fixedPriceCents ?? null,
      input.notes ?? null,
      ...assignmentArrays(input.helpers ?? []),
    ],
  );
  const created = rows[0];
  return created === undefined
    ? undefined
    : findJob(organizationId, created.id);
}

export async function updateJob(
  organizationId: string,
  id: string,
  patch: JobPatch,
): Promise<Job | undefined> {
  const set = buildSetClause(patch, patchableColumns, 3);
  if (set.values.length === 0 && patch.helpers === undefined) {
    return findJob(organizationId, id);
  }
  const values = [organizationId, id, ...set.values];

  let helpers = "";
  if (patch.helpers !== undefined) {
    values.push(...assignmentArrays(patch.helpers));
    const ids = `$${values.length - 1}`;
    const rates = `$${values.length}`;
    helpers = `,
     ${unassignOtherHelpers(jobHelpers, "updated", ids)},
     ${assignHelpers(jobHelpers, "updated", ids, rates)}`;
  }

  // A patch of the helpers alone still changes the job.
  const assignments = [set.assignments, "updated_at = now()"]
    .filter((assignment) => assignment !== "")
    .join(", ");
  const { rows } = await pool.query<{ id: string }>(
    `WITH updated AS (
       UPDATE jobs
       SET ${assignments}
       WHERE organization_id = $1 AND id = $2
       RETURNING organization_id, id
     )${helpers}
     SELECT id FROM updated`,
    values,
  );
  return rows[0] === undefined ? undefined : findJob(organizationId, id);
}

export async function deleteJob(
  organizationId: string,
  id: string,
): Promise<boolean> {
  const { rowCount } = await pool.query(
    "DELETE FROM jobs WHERE organization_id = $1 AND id = $2",
    [organizationId, id],
  );
  return (rowCount ?? 0) > 0;
}
